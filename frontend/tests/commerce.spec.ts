test('new commerce pages fit desktop and mobile', async ({ page }, testInfo) => {
  await mockApi(page); await login(page, memberSession)
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  for (const path of ['/shop', '/member/recharge', '/member/consumption', '/member/card', '/member/orders']) {
    await page.goto(path); await expect(page.locator('.skeleton-row')).toHaveCount(0)
    if (path === '/shop') await expect(page.locator('.shop-product')).toHaveCount(5)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), path).toBeTruthy()
  }
  await page.goto('/shop'); await expect(page.locator('.shop-product')).toHaveCount(5)
  await page.screenshot({ path: testInfo.outputPath('shop.png'), fullPage: true })
  expect(errors).toEqual([])
})
