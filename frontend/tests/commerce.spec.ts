test('insufficient card balance blocks purchase and failed submit keeps retry key', async ({ page }) => {
  const api = await mockApi(page); api.db.membershipCard![0]!.balance = 1
  await login(page, memberSession); await page.goto('/shop')
  await page.locator('.shop-product').filter({ hasText: '运动饮料' }).getByRole('button', { name: '立即购买' }).click()
  await page.getByRole('button', { name: '确认支付' }).click()
  await expect(page.getByRole('alert')).toContainText('余额不足')
  expect(api.requests.filter(item => item.action === 'checkout')).toHaveLength(0)
  await page.getByRole('button', { name: '取消', exact: true }).click()
  api.db.membershipCard![0]!.balance = 100; api.control.businessError = '暂时无法完成结算'
  await page.locator('.shop-product').filter({ hasText: '运动饮料' }).getByRole('button', { name: '立即购买' }).click()
  await page.getByRole('button', { name: '确认支付' }).click()
  await expect(page.getByRole('alert')).toContainText('暂时无法完成结算')
  await page.getByRole('button', { name: '确认支付' }).click()
  await expect.poll(() => api.requests.filter(item => item.action === 'checkout').length).toBe(2)
  const retries = api.requests.filter(item => item.action === 'checkout')
  expect(retries[0]!.data.requestNo).toBe(retries[1]!.data.requestNo)
})

