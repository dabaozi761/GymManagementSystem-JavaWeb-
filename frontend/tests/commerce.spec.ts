test('member orders use shop order endpoints for list filters refresh and detail', async ({ page }) => {
  const api = await mockApi(page); await login(page, memberSession)
  api.db.shopOrder!.push({ ...api.db.shopOrder![0], id: 2, orderNo: 'SOOTHER', memberId: 2, memberName: '李沐' })
  await page.goto('/member/orders')
  const order = page.getByRole('row').filter({ hasText: 'SO1' })
  await expect(order).toBeVisible()
  await expect(page.getByRole('row').filter({ hasText: 'SOOTHER' })).toHaveCount(0)
  expect(api.requests.find(item => item.action === 'page')!.resource).toBe('shopOrder')
  await page.getByRole('button', { name: /筛选/ }).click()
  await expect(page.locator('#filter-memberId')).toHaveCount(0)
  await page.locator('#filter-status').selectOption('2'); await page.getByRole('button', { name: '应用筛选' }).click()
  await expect(order).toBeVisible()
  const filtered = api.requests.filter(item => item.action === 'page').at(-1)!
  expect(filtered.resource).toBe('shopOrder'); expect(filtered.data.status).toBe(2)
  await page.getByRole('button', { name: '刷新列表' }).click()
  await expect(order).toBeVisible()
  await order.getByRole('button', { name: '详情', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('储物柜租用')
  expect(api.requests.find(item => item.action === 'detail')).toMatchObject({ resource: 'shopOrder', method: 'GET', data: { id: '1' } })
  expect(api.requests.some(item => item.resource === 'memberOrders')).toBeFalsy()
  await expect(page.getByRole('button', { name: '确认归还', exact: true })).toHaveCount(0)
})

