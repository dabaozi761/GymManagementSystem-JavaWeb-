test('four card types share balances and edits do not submit balance', async ({ page }) => {
  const api = await mockApi(page); await login(page); await page.goto('/membershipCard')
  await page.getByRole('button', { name: '新增会员卡', exact: true }).click()
  await expect(page.locator('#edit-cardType option:not([value=""])')).toHaveCount(4)
  await expect(page.locator('#edit-cardType option[value="5"]')).toHaveCount(0)
  await expect(page.locator('#edit-balance')).toBeVisible()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  const row = page.getByRole('row').filter({ hasText: 'C202609290002' })
  await row.getByRole('button', { name: '编辑', exact: true }).click()
  await expect(page.locator('#edit-balance')).toHaveCount(0)
  await page.getByRole('button', { name: '保存信息' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(api.requests.find(item => item.action === 'update')!.data.balance).toBeUndefined()
  await row.locator('summary').click(); await row.getByRole('button', { name: '余额扣费', exact: true }).click()
  await page.getByLabel('消费金额（元）').fill('12.50')
  await page.getByRole('button', { name: '确认余额扣费' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(api.requests.find(item => item.action === 'consume')!.data).toEqual({ id: 2, amount: 12.5 })
})

